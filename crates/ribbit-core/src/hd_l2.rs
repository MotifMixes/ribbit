//! EXPERIMENTAL: HD hooks for the Leapster 2 family's Flash player
//! (Leapster 2 BIOS 0.6 152-12206, Leapster Connected B5 152-12076, CIP3
//! m9 152-12659). See hd.rs for what each hook observes.
//!
//! These BIOSes carry a later build of the same player ("./src/core/
//! renderer.cpp" etc., with its asserts left in; VERIFIED-FW: the assert line
//! numbers match US v2.1's, e.g. renderer.cpp 3542, splay.cpp 1002/1042/1117),
//! compiled by another compiler: the functions do the same with the same
//! structures (edge record, fill style, renderer object at the same offsets),
//! but none of hd.rs's byte signatures matches. Two builds: A (0.6 and B5,
//! the same code at other addresses) and B (m9, compiled differently again).
//! Signatures are masked (`W`) where they hold absolute addresses, calls or
//! branches.

use super::{Build, GlyphRegs, Hooks, INDEX_PAST, W, find_masked};

/// One build's signatures, offsets and registers.
struct Table {
    /// The edge constructor (r1 the edge record; 0.6 0x4007_40B8, m9 0x4007_3ED0).
    edge: &'static [u16],
    /// PaintActive (one scanline: 0.6 0x4007_6894, m9 0x4007_65B8), and the
    /// hook inside it, where both setup paths join (0.6 0x4007_6912, m9
    /// 0x4007_6616), with the renderer object's and y + 1's registers.
    scan: &'static [u16],
    scan_at: u32,
    renderer: u8,
    scan_y: u8,
    /// The fill-style setup's bitmap and gradient cases (0.6 0x4007_3B2A and
    /// 0x4007_3D42, m9 0x4007_39C8 and 0x4007_3BD0), which store the span
    /// painters into fill +0x20 from `mov_s r, limm`: the offsets of those
    /// instructions (solid, bitmap blend, bitmap; gradient blend, gradient).
    bitmap_block: &'static [u16],
    bitmap_at: (u32, u32, u32),
    gradient_block: &'static [u16],
    gradient_at: (u32, u32),
    /// The point transform (r0 matrix, r1 point, r2 result; 0.6 0x4006_FCA0,
    /// m9 0x4006_FCE8).
    transform: &'static [u16],
    /// The shape reader's straight/curve step (0.6 0x4008_6EDE, m9
    /// 0x4008_6B26): where the transform returns for a straight edge's end,
    /// a curve's control point and a curve's end, and the curve's register.
    shape: &'static [u16],
    shape_at: (u32, u32, u32),
    curve: u8,
    /// The stroker's "add a piece" (0.6 0x4009_7A20, m9 0x4009_72F4).
    stroke: &'static [u16],
}

