/// The 32-bit immediate of the `mov_s r, limm` at `at` (ARCompact keeps it
/// as two little-endian halves, the high one first).
fn limm(bios: &[u8], base: u32, at: u32) -> Option<u32> {
    let o = at.checked_sub(base)? as usize + 2;
    let h = |i: usize| bios.get(i..i + 2).map(|b| u16::from_le_bytes([b[0], b[1]]) as u32);
    Some(h(o)? << 16 | h(o + 2)?)
}

/// The hooks of a Leapster 2 family BIOS mapped at `base` (None unless the
/// edge constructor, the scanline hook and the painters are all found).
pub(super) fn find(bios: &[u8], base: u32) -> Option<Hooks> {
    [BUILD_A, BUILD_B].iter().find_map(|t| find_build(t, bios, base))
}

fn find_build(t: &Table, bios: &[u8], base: u32) -> Option<Hooks> {
    let edge_ctor = find_masked(bios, base, t.edge)?;
    let scanline = find_masked(bios, base, t.scan)? + t.scan_at;
    let b = find_masked(bios, base, t.bitmap_block)?;
    let g = find_masked(bios, base, t.gradient_block);
    let shape = find_masked(bios, base, t.shape);
    Some(Hooks {
        edge_ctor,
        scanline,
        solid_painter: limm(bios, base, b + t.bitmap_at.0)?,
        bitmap_painter: limm(bios, base, b + t.bitmap_at.2)?,
        glyph: find_masked(bios, base, &GLYPH_A).map(|a| a + GLYPH_AT),
        glyph_regs: GLYPH_REGS,
        gradient: g.and_then(|g| limm(bios, base, g + t.gradient_at.1)),
        gradient_blend: g.and_then(|g| limm(bios, base, g + t.gradient_at.0)),
        bitmap_blend: limm(bios, base, b + t.bitmap_at.1),
        transform: find_masked(bios, base, t.transform),
        // The shape reader's last site stands for it (see `Build::sites`).
        shape_curve: shape.map(|s| s + t.shape_at.2),
        stroke: find_masked(bios, base, t.stroke),
        build: Build {
            renderer: t.renderer,
            scan_y: t.scan_y,
            curve: t.curve,
            sites: shape.map(|s| (s + t.shape_at.0, s + t.shape_at.1, s + t.shape_at.2)),
        },
    })
}
