"""Generates Ribbit's WGSL port of the Anime4K CNN x2 upscalers.

Input:  a checkout of https://github.com/bloc97/Anime4K (MIT, (c) 2019-2021
        bloc97), default tools/ref/anime4k/src (git-ignored).
Output: crates/ribbit-frontend/src/upscale/anime4k_<size>.rs

Run:    python -I scripts/gen-anime4k.py [--src DIR]

Each mpv hook pass becomes one WGSL fragment shader. The trained weights are
copied verbatim; GLSL `mat4(16 floats) * vec4` and WGSL `mat4x4<f32>(...) *
vec4<f32>` are both column-major, so the numbers keep their meaning. Texture
reads are integer `textureLoad`s at the output pixel plus the tap offset,
clamped at the edges (mpv's texOff at texel centres with clamp-to-edge).
"""
