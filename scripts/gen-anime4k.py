COMMON = """
var<private> P: vec2<i32>;

fn tap(t: texture_2d<f32>, x: f32, y: f32) -> vec4<f32> {
    let size = vec2<i32>(textureDimensions(t));
    return textureLoad(t, clamp(P + vec2<i32>(i32(x), i32(y)), vec2<i32>(0), size - vec2<i32>(1)), 0);
}
"""


def parse(path):
    text = path.read_text(encoding='utf-8')
    passes = []
    for block in text.split('//!DESC ')[1:]:
        lines = block.splitlines()
        desc = lines[0].strip()
        binds = [l.split()[1] for l in lines if l.startswith('//!BIND ')]
        save = next(l.split()[1] for l in lines if l.startswith('//!SAVE '))
        defines = [l for l in lines if l.startswith('#define ')]
        body_start = next(i for i, l in enumerate(lines) if l.startswith('vec4 hook()'))
        body = lines[body_start + 1:]
        body = body[:next(i for i, l in enumerate(body) if l.startswith('}'))]
        passes.append({'desc': desc, 'binds': binds, 'save': save, 'defines': defines, 'body': body})
    return passes


DEF_TAP = re.compile(r'#define (go_\d+)\(x_off, y_off\) \((max\()?(-)?\(?(\w+?)_texOff\(vec2\(x_off, y_off\)\)\)?(, 0\.0\))?\)$')
DEF_CENTRE = re.compile(r'#define (g_\d+) \(max\((-)?\((\w+?)_tex\(\w+?_pos\)\), 0\.0\)\)$')


def conv_wgsl(p):
    binds = p['binds']
    out = [COMMON]
    for i, b in enumerate(binds):
        out.append(f'@group(0) @binding({i}) var t{i}: texture_2d<f32>; // {b}')
    for d in p['defines']:
        m = DEF_TAP.match(d)
        if m:
            name, relu, neg, tex = m.group(1), m.group(2), m.group(3), m.group(4)
            v = f'tap(t{binds.index(tex)}, x, y)'
            if neg:
                v = f'-{v}'
            if relu:
                v = f'max({v}, vec4<f32>(0.0))'
            out.append(f'fn {name}(x: f32, y: f32) -> vec4<f32> {{ return {v}; }}')
            continue
        m = DEF_CENTRE.match(d)
        if m:
            name, neg, tex = m.group(1), m.group(2), m.group(3)
            v = f'tap(t{binds.index(tex)}, 0.0, 0.0)'
            if neg:
                v = f'-{v}'
            out.append(f'fn {name}() -> vec4<f32> {{ return max({v}, vec4<f32>(0.0)); }}')
            continue
        sys.exit(f'unhandled define in {p["desc"]}: {d}')
    out.append('@fragment\nfn fs(@builtin(position) pos: vec4<f32>) -> @location(0) vec4<f32> {')
    out.append('    P = vec2<i32>(pos.xy);')
    for line in p['body']:
        s = line.strip()
        s = s.replace('vec4 result =', 'var result: vec4<f32> =')
        s = s.replace('mat4(', 'mat4x4<f32>(').replace('vec4(', 'vec4<f32>(')
        s = re.sub(r'\b(g_\d+)\b(?!\()', r'\1()', s)
        # Restore models end by adding their result to the input.
        if s == 'return result + MAIN_tex(MAIN_pos);':
            s = f'return result + tap(t{binds.index("MAIN")}, 0.0, 0.0);'
        if not re.fullmatch(r'(var result: vec4<f32> =|result \+=|return result).*', s):
            sys.exit(f'unhandled statement in {p["desc"]}: {s[:80]}')
        out.append('    ' + s)
    out.append('}')
    return '\n'.join(out)


def d2s_wgsl(p):
    lasts = [b for b in p['binds'] if b != 'MAIN']
    assert p['binds'][0] == 'MAIN' and len(lasts) in (1, 3), p['binds']
    out = ['@group(0) @binding(0) var t0: texture_2d<f32>; // MAIN (stage input)']
    for i, b in enumerate(lasts):
        out.append(f'@group(0) @binding({i + 1}) var t{i + 1}: texture_2d<f32>; // {b}')
    out.append("""
fn texel(p: vec2<i32>) -> vec4<f32> {
    let size = vec2<i32>(textureDimensions(t0));
    return textureLoad(t0, clamp(p, vec2<i32>(0), size - vec2<i32>(1)), 0);
}

// mpv samples MAIN bilinearly at the output position.
fn bilinear(q: vec2<f32>) -> vec4<f32> {
    let b = floor(q);
    let f = q - b;
    let i = vec2<i32>(b);
    let top = mix(texel(i), texel(i + vec2<i32>(1, 0)), f.x);
    let bottom = mix(texel(i + vec2<i32>(0, 1)), texel(i + vec2<i32>(1, 1)), f.x);
    return mix(top, bottom, f.y);
}

@fragment
fn fs(@builtin(position) pos: vec4<f32>) -> @location(0) vec4<f32> {
    let q = vec2<i32>(pos.xy);
    let src = q / 2;
    let k = (q.y % 2) * 2 + q.x % 2;""")
    for i in range(len(lasts)):
        out.append(f'    let c{i} = textureLoad(t{i + 1}, src, 0)[k];')
    if len(lasts) == 1:
        out.append('    let detail = vec3<f32>(c0);')
    else:
        out.append('    let detail = vec3<f32>(c0, c1, c2);')
    out.append('    let base = bilinear(pos.xy * 0.5 - 0.5);')
    out.append('    return vec4<f32>(base.rgb + detail, 1.0);')
    out.append('}')
    return '\n'.join(out)


def generate(src, folder, stem, size, module):
    path = src / 'glsl' / folder / f'Anime4K_{stem}_{size}.glsl'
    passes = parse(path)
    rs = [HEADER]
    rs.append(f'//! Anime4K v3.2 {stem} ({size}): {len(passes)} passes.\n')
    rs.append('use super::{Pass, PassKind};\n')
    rs.append('pub const PASSES: &[Pass] = &[')
    for p in passes:
        d2s = 'Depth-to-Space' in p['desc']
        wgsl = d2s_wgsl(p) if d2s else conv_wgsl(p)
        kind = 'PassKind::DepthToSpace' if d2s else 'PassKind::Conv'
        inputs = ', '.join(f'"{b}"' for b in p['binds'])
        rs.append(f'    Pass {{\n        desc: "{p["desc"]}",\n        inputs: &[{inputs}],\n        outputs: &["{p["save"]}"],\n'
                  f'        kind: {kind},\n        wgsl: r#"{wgsl}\n"#,\n    }},')
    rs.append('];\n')
    out = OUT / f'{module}.rs'
    out.write_text('\n'.join(rs), encoding='utf-8')
    print(f'{out.relative_to(ROOT)}: {len(passes)} passes')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', type=Path, default=ROOT / 'tools' / 'ref' / 'anime4k' / 'src')
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for folder, stem, size, module in MODELS:
        generate(a.src, folder, stem, size, module)


if __name__ == '__main__':
    main()
