"""Regenerates Ribbit's table of known Leapster cartridges from MAME's software
list (hash/leapster.xml, CC0-1.0). Only names, serials and checksums are
copied: no image data.

Usage (from the repository root):
    python scripts/gen-known-carts.py path/to/leapster.xml

The list is at https://github.com/mamedev/mame/blob/master/hash/leapster.xml.
Writes crates/ribbit-memory/src/known_carts.rs.
"""

import sys
import xml.etree.ElementTree as ET

OUT = "crates/ribbit-memory/src/known_carts.rs"


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = ET.parse(sys.argv[1]).getroot()
    rows = []
    for sw in root.findall("software"):
        desc = sw.findtext("description").strip()
        serial = next((i.get("value") for i in sw.findall("info") if i.get("name") == "serial"), None)
        for rom in sw.iter("rom"):
            if not rom.get("crc") or not rom.get("sha1"):
                continue
            name = desc
            if serial:
                name += f" [{serial}]"
            name += f" (MAME: {sw.get('name')})"
            bad = rom.get("status") == "baddump"
            rows.append((desc.lower(), name, int(rom.get("size"), 0), int(rom.get("crc"), 16), rom.get("sha1"), bad))
    rows.sort()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen-known-carts.py from MAME's hash/leapster.xml\n")
        f.write("// (CC0-1.0): names, serials and checksums only. Do not edit by hand.\n\n")
        f.write("use crate::known::{Hardware, KnownImage, fw};\n\n")
        f.write("/// Leapster cartridges in MAME's software list.\n")
        f.write("pub const CARTRIDGES: &[KnownImage] = &[\n")
        for _, name, size, crc, sha1, bad in rows:
            f.write(f"    fw(\n        {rust_str(name)},\n        Hardware::Leapster,\n")
            f.write(f"        {size:#x},\n        {crc:#010x},\n        {rust_str(sha1)},\n        {str(bad).lower()},\n    ),\n")
        f.write("];\n")
    print(f"{len(rows)} cartridges -> {OUT}")


if __name__ == "__main__":
    main()
