import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'crates' / 'ribbit-frontend' / 'src' / 'upscale'
MODELS = ['C4F16', 'C4F32']
MAX_TARGETS = 4

