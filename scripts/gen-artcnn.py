TAP = """
var<private> P: vec2<i32>;

// Zero outside the picture (the network's training padding).
fn tap(t: texture_2d<f32>, x: i32, y: i32) -> vec4<f32> {
    let q = P + vec2<i32>(x, y);
    let size = vec2<i32>(textureDimensions(t));
    if (any(q < vec2<i32>(0)) || any(q >= size)) {
        return vec4<f32>(0.0);
    }
    return textureLoad(t, q, 0);
}
"""

YUV_PASS = """
@group(0) @binding(0) var t0: texture_2d<f32>; // MAIN (RGB)

// Full-range BT.601, chroma offset by 0.5 (as the libretro ArtCNN port).
@fragment
fn fs(@builtin(position) pos: vec4<f32>) -> @location(0) vec4<f32> {
    let c = textureLoad(t0, vec2<i32>(pos.xy), 0).rgb;
    let y = dot(c, vec3<f32>(0.299, 0.587, 0.114));
    let u = (c.b - y) / 1.772;
    let v = (c.r - y) / 1.402;
    return vec4<f32>(y, u + 0.5, v + 0.5, 1.0);
}
"""

D2S_PASS = """
@group(0) @binding(0) var t0: texture_2d<f32>; // conv2d_6 (4 sub-pixel lumas)
@group(0) @binding(1) var t1: texture_2d<f32>; // yuv (1x)

fn texel(p: vec2<i32>) -> vec4<f32> {
    let size = vec2<i32>(textureDimensions(t1));
    return textureLoad(t1, clamp(p, vec2<i32>(0), size - vec2<i32>(1)), 0);
}

fn catmull_rom(t: f32) -> vec4<f32> {
    let t2 = t * t;
    let t3 = t2 * t;
    return vec4<f32>(
        -0.5 * t3 + t2 - 0.5 * t,
        1.5 * t3 - 2.5 * t2 + 1.0,
        -1.5 * t3 + 2.0 * t2 + 0.5 * t,
        0.5 * t3 - 0.5 * t2,
    );
}

// 2x chroma, Catmull-Rom.
fn chroma(p: vec2<f32>) -> vec2<f32> {
    let q = p - 0.5;
    let base = floor(q);
    let f = q - base;
    let wx = catmull_rom(f.x);
    let wy = catmull_rom(f.y);
    let b = vec2<i32>(base);
    var acc = vec2<f32>(0.0);
    for (var j = 0; j < 4; j++) {
        var row = vec2<f32>(0.0);
        for (var i = 0; i < 4; i++) {
            row += texel(b + vec2<i32>(i - 1, j - 1)).yz * wx[i];
        }
        acc += row * wy[j];
    }
    return acc - 0.5;
}

@fragment
fn fs(@builtin(position) pos: vec4<f32>) -> @location(0) vec4<f32> {
    let q = vec2<i32>(pos.xy);
    let k = (q.y % 2) * 2 + q.x % 2;
    let y = clamp(textureLoad(t0, q / 2, 0)[k], 0.0, 1.0);
    let uv = chroma(pos.xy * 0.5);
    let rgb = vec3<f32>(y + 1.402 * uv.y, y - 0.344136 * uv.x - 0.714136 * uv.y, y + 1.772 * uv.x);
    return vec4<f32>(clamp(rgb, vec3<f32>(0.0), vec3<f32>(1.0)), 1.0);
}
"""


def parse(path):
    text = path.read_text(encoding='utf-8')
    passes = []
    for block in text.split('//!DESC ')[1:]:
        lines = block.splitlines()
        p = {
            'desc': lines[0].strip(),
            'binds': [l.split()[1] for l in lines if l.startswith('//!BIND ')],
            'save': next((l.split()[1] for l in lines if l.startswith('//!SAVE ')), None),
            'lines': [l.strip() for l in lines],
        }
        passes.append(p)
    return passes


FETCH = re.compile(r'texelFetch\((\w+)_raw, input_base \+ ivec2\((\d+), (\d+)\), 0\)(\.x)?')
INP = re.compile(r'inp\[(\d+)\]\[y\]\[x\] = (.*);$')
DECL = re.compile(r'const (?:F|V4) (inp_(\d+)_(\d+)_(\d+)) = inp\[\d+\]\[local_xy\.y \+ \d+\]\[local_xy\.x \+ \d+\];$')
INIT = re.compile(r'V4 (result\d+) = V4\((.*)\);$')
ACC = re.compile(r'(result\d+) \+= (V4|M4)\((.*)\) \* (inp_\d+_\d+_\d+);$')
STORE = re.compile(r'imageStore\(out_image, output_base \+ ivec2\((\d+), (\d+)\), (max\()?(result\d+)(, V4\(0\.0\)\))?\);$')


def tex_name(tensor, dx, dy):
    return 'yuv' if tensor == 'LUMA' else f'{tensor}_{dx}{dy}'


def conv_passes(p):
    """One mpv conv pass -> one or more Ribbit passes (<= 4 outputs each)."""
    inputs = {}  # inp index -> [(texture, luma?)]
    decls = {}  # inp_K_X_Y -> (K, X, Y)
    inits, accs, stores = {}, {}, []
    for l in p['lines']:
        m = INP.match(l)
        if m:
            k = int(m.group(1))
            inputs[k] = [(tex_name(f[0], f[1], f[2]), bool(f[3])) for f in FETCH.findall(m.group(2))]
            assert inputs[k], l
            continue
        m = DECL.match(l)
        if m:
            decls[m.group(1)] = (int(m.group(2)), int(m.group(3)), int(m.group(4)))
            continue
        m = INIT.match(l)
        if m:
            inits[m.group(1)] = m.group(2)
            continue
        m = ACC.match(l)
        if m:
            accs.setdefault(m.group(1), []).append((m.group(2), m.group(3), m.group(4)))
            continue
        m = STORE.match(l)
        if m:
            stores.append((m.group(4), f'{p["save"]}_{m.group(1)}{m.group(2)}', bool(m.group(3))))
            continue
        if l.startswith(('result', 'V4 result', 'imageStore', 'inp[')):
            sys.exit(f'{p["desc"]}: unhandled line {l[:80]}')
    assert stores and set(r for r, _, _ in stores) == set(inits), p['desc']
    textures = []
    for k in sorted(inputs):
        for t, _ in inputs[k]:
            if t not in textures:
                textures.append(t)
    out = []
    for g in range(0, len(stores), MAX_TARGETS):
        group = stores[g:g + MAX_TARGETS]
        w = [TAP]
        for i, t in enumerate(textures):
            w.append(f'@group(0) @binding({i}) var t{i}: texture_2d<f32>; // {t}')
        for k in sorted(inputs):
            parts = [f'tap(t{textures.index(t)}, x, y)' + ('.x' if luma else '') for t, luma in inputs[k]]
            ty = 'f32' if all(luma for _, luma in inputs[k]) else 'vec4<f32>'
            w.append(f'fn in{k}(x: i32, y: i32) -> {ty} {{ return {" + ".join(parts)}; }}')
        w.append('struct Out {')
        for j, (_, name, _) in enumerate(group):
            w.append(f'    @location({j}) o{j}: vec4<f32>, // {name}')
        w.append('}')
        w.append('@fragment\nfn fs(@builtin(position) pos: vec4<f32>) -> Out {')
        w.append('    P = vec2<i32>(pos.xy);')
        used = sorted({a[2] for r, _, _ in group for a in accs.get(r, [])}, key=lambda d: decls[d])
        for d in used:
            k, x, y = decls[d]
            w.append(f'    let {d} = in{k}({x - 1}, {y - 1});')
        for r, _, _ in group:
            w.append(f'    var {r} = vec4<f32>({inits[r]});')
            for kind, nums, operand in accs.get(r, []):
                ctor = 'vec4<f32>' if kind == 'V4' else 'mat4x4<f32>'
                w.append(f'    {r} += {ctor}({nums}) * {operand};')
        w.append('    var o: Out;')
        for j, (r, _, relu) in enumerate(group):
            w.append(f'    o.o{j} = ' + (f'max({r}, vec4<f32>(0.0));' if relu else f'{r};'))
        w.append('    return o;\n}')
        part = f' [{g // MAX_TARGETS + 1}/{(len(stores) + MAX_TARGETS - 1) // MAX_TARGETS}]' if len(stores) > MAX_TARGETS else ''
        out.append({
            'desc': p['desc'] + part,
            'inputs': textures,
            'outputs': [name for _, name, _ in group],
            'kind': 'Conv',
            'wgsl': '\n'.join(w),
        })
    return out


def generate(src, model):
    passes = parse(src / 'GLSL' / f'ArtCNN_{model}.glsl')
    assert 'Depth-To-Space' in passes[-1]['desc'], passes[-1]['desc']
    out = [{'desc': f'ArtCNN {model} (RGB to YUV)', 'inputs': ['MAIN'], 'outputs': ['yuv'], 'kind': 'Conv', 'wgsl': YUV_PASS}]
    for p in passes[:-1]:
        out += conv_passes(p)
    last = out[-1]['outputs']
    assert last == ['conv2d_6_00'], last
    out.append({'desc': f'ArtCNN {model} (Depth-To-Space + chroma)', 'inputs': ['conv2d_6_00', 'yuv'],
                'outputs': ['MAIN'], 'kind': 'DepthToSpace', 'wgsl': D2S_PASS})
    rs = [HEADER, f'//! ArtCNN {model} 2x (luma network + Catmull-Rom chroma): {len(out)} passes.\n',
          'use super::{Pass, PassKind};\n', 'pub const PASSES: &[Pass] = &[']
    for p in out:
        ins = ', '.join(f'"{i}"' for i in p['inputs'])
        outs = ', '.join(f'"{o}"' for o in p['outputs'])
        rs.append(f'    Pass {{\n        desc: "{p["desc"]}",\n        inputs: &[{ins}],\n        outputs: &[{outs}],\n'
                  f'        kind: PassKind::{p["kind"]},\n        wgsl: r#"{p["wgsl"]}\n"#,\n    }},')
    rs.append('];\n')
    path = OUT / f'artcnn_{model.lower()}.rs'
    path.write_text('\n'.join(rs), encoding='utf-8')
    print(f'{path.relative_to(ROOT)}: {len(out)} passes')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', type=Path, default=ROOT / 'tools' / 'ref' / 'artcnn' / 'src')
    a = ap.parse_args()
    for model in MODELS:
        generate(a.src, model)


if __name__ == '__main__':
    main()
