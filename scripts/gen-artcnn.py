"""Generates Ribbit's WGSL port of the ArtCNN 2x luma upscalers.

Input:  a checkout of https://github.com/Artoriuz/ArtCNN (MIT, (c) 2024 Joao
        Chrisostomo, Kacper Michajlow), default tools/ref/artcnn/src
        (git-ignored).
Output: crates/ribbit-frontend/src/upscale/artcnn_<model>.rs

Run:    python -I scripts/gen-artcnn.py [--src DIR]

The mpv originals are compute shaders that keep each layer's 16 or 32
channels as tiles (2x2 or 4x2 vec4 cells per pixel) of one texture. Here
every tile is its own Rgba16Float texture and each layer is a fragment pass
writing up to four of them at once (the portable 32-byte render-target
limit), so 32-channel layers take two passes. Trained weights are copied
verbatim; GLSL and WGSL matrices are both column-major. Out-of-range taps
read zero, matching the zero ("same") padding the network was trained with.

ArtCNN works on luma only: a first pass converts RGB to full-range BT.601
YUV, and the last pass places the network's 2x luma next to Catmull-Rom 2x
chroma and converts back (as the libretro port does, with Jinc2 there).
"""
